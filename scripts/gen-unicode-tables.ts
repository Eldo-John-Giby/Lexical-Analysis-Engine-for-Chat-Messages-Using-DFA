// ALLOWED-REGEXP: build-time range generation for unicode character classes
import * as fs from 'node:fs';
import * as path from 'node:path';

interface Interval {
  lo: number;
  hi: number;
}

function findRanges(predicate: (cp: number) => boolean, maxCp = 0x10FFFF): Interval[] {
  const ranges: Interval[] = [];
  let inRange = false;
  let start = 0;

  for (let cp = 0; cp <= maxCp; cp++) {
    const match = predicate(cp);
    if (match && !inRange) {
      inRange = true;
      start = cp;
    } else if (!match && inRange) {
      inRange = false;
      ranges.push({ lo: start, hi: cp - 1 });
    }
  }
  if (inRange) {
    ranges.push({ lo: start, hi: maxCp });
  }
  return ranges;
}

console.log('Generating Unicode tables...');

const isLetterRegex = /^\p{L}$/u;
const isMarkRegex = /^\p{M}$/u;
const isEpRegex = /^\p{Extended_Pictographic}$/u;

const letterRanges = findRanges((cp) => {
  try {
    const s = String.fromCodePoint(cp);
    return isLetterRegex.test(s);
  } catch {
    return false;
  }
});

const markRanges = findRanges((cp) => {
  try {
    const s = String.fromCodePoint(cp);
    return isMarkRegex.test(s);
  } catch {
    return false;
  }
});

// EP: Extended_Pictographic with code point > 0xFF (excludes (c) (r) TM digits)
const epRanges = findRanges((cp) => {
  if (cp <= 0xFF) return false;
  try {
    const s = String.fromCodePoint(cp);
    return isEpRegex.test(s);
  } catch {
    return false;
  }
});

function serializeRanges(ranges: Interval[]): string {
  return JSON.stringify(ranges);
}

const fileContent = `// Auto-generated by scripts/gen-unicode-tables.ts - DO NOT EDIT MANUALLY
// Generated on ${new Date().toISOString()}

export interface Interval {
  lo: number;
  hi: number;
}

export const UNICODE_LETTER_RANGES: readonly Interval[] = ${serializeRanges(letterRanges)} as const;

export const UNICODE_MARK_RANGES: readonly Interval[] = ${serializeRanges(markRanges)} as const;

export const UNICODE_EP_RANGES: readonly Interval[] = ${serializeRanges(epRanges)} as const;
`;

const outputPath = path.resolve(process.cwd(), 'src/engine/unicode-tables.generated.ts');
fs.writeFileSync(outputPath, fileContent, 'utf-8');
console.log(`Unicode tables generated successfully at ${outputPath}`);
console.log(`Letter ranges: ${letterRanges.length}, Mark ranges: ${markRanges.length}, EP ranges: ${epRanges.length}`);
